export function localizeMessage(message: string | null | undefined, language: AppLanguage) {
  if (!message) return undefined;
  if (language === "en") return message;
  const photoLimit = message.match(/^Upload no more than (\d+) photos\.$/);
  if (photoLimit) return `Unggah maksimal ${photoLimit[1]} foto.`;
  const videoLimit = message.match(/^The issue video must be no larger than (\d+) MB\.$/);
  if (videoLimit) return `Ukuran video kendala maksimal ${videoLimit[1]} MB.`;
  return indonesianValidationMessages[message] ?? message;
}
